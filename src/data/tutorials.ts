export function getTutorial(idOrSlug: string) {
  return tutorials.find((t) => t.id === idOrSlug || t.slug === idOrSlug);
}

export function tutorialsByGame(gameId: string) {
  return tutorials.filter((t) => t.gameId === gameId);
}

export function tutorialsByCreator(creatorId: string) {
  return tutorials.filter((t) => t.creatorId === creatorId);
}
